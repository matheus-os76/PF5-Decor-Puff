    public void mostrarCatalogo()
    {        
        Model_Catalago.setRowCount(0);

        
        int j = 0;
        for (int i = (PAGINA_ATUAL - 1) * ITENS_POR_PAGINA; i < (ITENS_POR_PAGINA * PAGINA_ATUAL) && i < QUANTIDADE_ITENS; i++) {
            
            Item item = DB.getItem(i+1);
              
            Model_Catalago.insertRow(j, new Object[]{
                item.ID,
                item.Nome,
                item.Categoria.name(),
                item.Quantidade,
                item.Descricao,
                item.Valor_Venda,
                item.Valor_Aluguel,
                item.Status.name()
            });
            
            j++;
        }
    }
    
