    private void btn_Finalizar_PedidoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_Finalizar_PedidoActionPerformed
        
        for (int i = 0; i < this.pedido.Itens.size(); i++)
        {
            this.pedido.Itens.get(i).Quantidade = (int) Model_Pedido.getValueAt(i, 2);
        }
        
        DB.addPedido(this.pedido);
        
        JOptionPane.showMessageDialog(this, "Pedido realizado!");
        
        this.pedido = null;
        
        Model_Pedido.setRowCount(0);
    }//GEN-LAST:event_btn_Finalizar_PedidoActionPerformed

