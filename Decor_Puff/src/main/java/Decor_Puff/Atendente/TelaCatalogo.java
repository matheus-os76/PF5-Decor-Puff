    private void btn_AddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_AddActionPerformed
        
        try {
            
            int[] linhas_selecionadas = tab_Catalogo.getSelectedRows();
            ArrayList<ItemDAO> lista = new ArrayList<ItemDAO>(linhas_selecionadas.length);

            for (int i = 0; i < linhas_selecionadas.length; i++)
            {

                Integer id = (Integer) Model_Catalago.getValueAt(linhas_selecionadas[i], 0);
                Item item = DB.getItem(id);

                if (item.Valor_Aluguel > 0)
                {
                    lista.add(new ItemDAO(item, 1, LocalDateTime.now().plusDays(3)));
                }
                else
                {
                    lista.add(new ItemDAO(item, 1));
                }
            }

            String path = JOptionPane.showInputDialog("Insira o CPF do cliente");

            CPF cpf = new CPF(path);
            var c = DB.getCliente(cpf);

            if (c == null)
            {
                JOptionPane.showMessageDialog(this, "Usuário inexistente!", "Erro", JOptionPane.ERROR_MESSAGE);
            }
            else
            {

                this.pedido = new Pedido(0, DB.getCliente(cpf), this.funcionario, LocalDateTime.now(), 50, 25, Status_Pedido.PROCESSANDO, lista);

                Model_Pedido.setRowCount(0);

                for (int j = 0; j < this.pedido.Itens.size(); j++)
                {
                    Model_Pedido.addRow(new Object[]{
                        pedido.Itens.get(j).Item.Nome,
                        pedido.Itens.get(j).Item.Categoria.name(),
                        pedido.Itens.get(j).Quantidade,
                        pedido.Itens.get(j).Data_Devolucao
                    });
                }
            }

        } 
        catch (Exception ex) 
        {
            JOptionPane.showMessageDialog(this, "Usuário inexistente!", "Erro", JOptionPane.ERROR_MESSAGE);
            System.getLogger(TelaCatalogo.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
        
    }//GEN-LAST:event_btn_AddActionPerformed

